export function toTraditionalTranslations(
  simplified: Record<string, string>
): Record<string, string> {
  return Object.fromEntries(Object.entries(simplified).map(([key, value]) => {
    let converted = value;
    for (const [from, to] of traditionalReplacements) {
      converted = converted.replaceAll(from, to);
    }
    return [key, converted];
  }));
}

